/**
 * Vite plugin for the browser build (`VITE_LOCI_TARGET=web`): adds the web app manifest, the
 * install and theme tags in index.html, and a service worker that precaches every file of the
 * build (app shell, scripts, styles, fonts, the WebAssembly engine, icons), so Loci starts offline
 * after the first visit. The cache name is a hash of the build, so each deploy installs a fresh
 * copy; the previous one is kept until the next deploy so an open tab can still lazy-load its chunks.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

export const MANIFEST = {
  name: 'Loci',
  short_name: 'Loci',
  description: 'A memory palace for everything you learn. Spaced repetition that imports your Anki collection.',
  id: './',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#f7f5f0',
  theme_color: '#f7f5f0',
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icons/icon.svg', sizes: 'any', type: 'image/svg+xml' },
    { src: 'icons/icon-maskable.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'maskable' },
  ],
};

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** The service worker source for a list of files (paths relative to the scope) and a version. */
export function serviceWorker(files: string[], version: string): string {
  return `// Loci service worker: precaches the whole build; generated by scripts/pwa.ts.
const CACHE = 'loci-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const ours = (await caches.keys()).filter((k) => k.startsWith('loci-') && k !== CACHE);
    // keep the newest previous build for tabs still running it
    for (const k of ours.slice(0, -1)) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  if (req.mode === 'navigate') {
    event.respondWith(caches.match('./', { ignoreSearch: true }).then((hit) => hit || fetch(req)).catch(() => fetch(req)));
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

export function pwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'loci-pwa',
    apply: 'build',
    configResolved(c) { config = c; },
    transformIndexHtml() {
      const base = config.base;
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: `${base}manifest.webmanifest` }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${base}icons/apple-touch-icon.png` }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#f7f5f0', media: '(prefers-color-scheme: light)' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#10141b', media: '(prefers-color-scheme: dark)' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
      ];
    },
    closeBundle() {
      const out = config.build.outDir;
      writeFileSync(join(out, 'manifest.webmanifest'), JSON.stringify(MANIFEST, null, 2));
      const files = walk(out)
        .map((p) => relative(out, p).split(sep).join('/'))
        .filter((f) => f !== 'sw.js' && !f.endsWith('.map'))
        .sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(out, f)));
      writeFileSync(join(out, 'sw.js'), serviceWorker(files, hash.digest('hex').slice(0, 16)));
    },
  };
}
